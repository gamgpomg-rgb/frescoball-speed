'use strict';
const assert = require('assert');
const Q = require('../video-quality.js');
const series = speeds => speeds.map((speed, i) => ({t: i * .4, speed, player: i % 2 ? 'b' : 'a', rNow: i + 1}));
const baseline = [60,61,59,60,105,61,60,59,61];
const input = series(baseline), snapshot = JSON.stringify(input);
const reviewed = Q.review(input);
assert.equal(reviewed.excluded, 1);
assert.equal(reviewed.candidates.length, 1);
assert.equal(reviewed.hits[4].speed, null);
assert.equal(reviewed.hits[4].originalSpeed, 105);
assert.equal(reviewed.hits[4].qualityCode, 'isolated_spike');
assert.equal(JSON.stringify(input), snapshot, 'must not mutate input');
assert.equal(reviewed.hits[4].player, input[4].player);
assert.equal(reviewed.hits[4].rNow, input[4].rNow);
assert.equal(Q.review(reviewed.hits, {autoOutliers:false}).hits[4].speed, 105, 'automatic review must be reversible');
assert.equal(Q.review(reviewed.hits, {overrides:{'1.6':'keep'}}).hits[4].speed, 105);
assert.equal(Q.review(input, {overrides:{'0.8':'drop'}}).hits[2].qualityCode, 'manual');
const limited = Q.review(series([70,80,90]), {maxSpeedKmh:80});
assert.equal(limited.excluded, 1);assert.equal(limited.hits[1].speed, 80);
assert.equal(limited.hits[2].qualityCode, 'above_limit');
assert.equal(Q.review(limited.hits, {maxSpeedKmh:100}).hits[2].speed, 90);
assert.equal(Q.review(limited.hits, {maxSpeedKmh:80,overrides:{'0.8':'keep'}}).hits[2].speed, 90);
assert.equal(Q.review(series([60,60,105,60,60])).candidates.length, 0, 'insufficient context');
assert.equal(Q.review(series([105,60,60,60,60,60,60])).candidates.length, 0, 'edge values need more context');
assert.equal(Q.review(series([60,61,60,60,105,107,60,61,60,60])).excluded, 0, 'adjacent fast shots are preserved');
assert.equal(Q.review(series([105,106,107,108,109,110,111,112,113])).excluded, 0, 'sustained fast rally preserved');
assert.equal(Q.review(series([40,41,39,40,80,41,40,39,40])).excluded, 1, 'not a hardcoded 105 km/h cutoff');
assert.equal(Q.review(series([60,90,50,85,105,45,90,65,90])).excluded, 0, 'high variation requires conservative review');
const gaps = series(baseline).map((h,i)=>({...h,t:i*4}));
assert.equal(Q.review(gaps).excluded, 0, 'do not connect separate rallies');
const absent = Q.review([{t:0,speed:null}], {overrides:{'0':'keep'}});
assert.equal(absent.hits[0].speed, null);assert.equal(absent.excluded, 0);
assert.equal(Q.review(absent.hits).hits[0].originalSpeed, null);
for (const limit of [0,-1,'',NaN,Infinity,true,[80]]) assert.throws(()=>Q.review(input, {maxSpeedKmh:limit}));
assert.throws(()=>Q.review([{t:NaN,speed:60}]));
console.log('Video quality isolation, reversibility, user limits and manual overrides passed');

const wholeVideo=series(Array.from({length:28},(_,i)=>40+(i%7)*5).concat(105));
const globalResult=Q.review(wholeVideo);
assert.equal(globalResult.hits.at(-1).speed,null,'whole-video distribution covers an isolated clip-edge peak');
assert.equal(globalResult.hits.at(-1).qualityCode,'global_isolated_spike');
assert.equal(globalResult.hits.at(-1).originalSpeed,105);
assert.match(globalResult.hits.at(-1).qualityReason,/動画全体/);
const supported=series(Array(30).fill(60));supported[0].speed=80;supported[25].speed=90;supported[12].speed=100;
assert.equal(Q.review(supported).hits[12].speed,100,'repeated 80/90 elsewhere support a local 100 peak');
assert.equal(Q.review(supported).hits[12].isOutlierCandidate,false);
const tooFew=series(Array(18).fill(55).concat(105));
assert.equal(Q.review(tooFew).hits.at(-1).speed,105,'global rule requires at least 20 usable samples');
const consecutive=series(Array(30).fill(55));consecutive[12].speed=105;consecutive[13].speed=110;
assert.equal(Q.review(consecutive).hits[12].speed,105);assert.equal(Q.review(consecutive).hits[13].speed,110);
const lastKey=String(wholeVideo.at(-1).t);
assert.equal(Q.review(globalResult.hits,{overrides:{[lastKey]:'keep'}}).hits.at(-1).speed,105);
assert.equal(Q.review(globalResult.hits,{autoOutliers:false}).hits.at(-1).speed,105);
assert.equal(Q.review(supported,{maxSpeedKmh:95}).hits[12].qualityCode,'above_limit','distribution support does not override explicit caps');
console.log('Whole-video isolated peaks, repeated upper-range support, minimum sample count and reversibility passed');

// Overlapping rallies from a neighbouring pair: keep the count, withhold speeds nearby.
{
  const single = Array.from({length: 12}, (_, i) => ({t: i * .7, speed: 55}));
  assert.equal(Q.review(single).overlapSuspects.length, 0, 'a steady single rally is not suspect');
  const fast = Array.from({length: 10}, (_, i) => ({t: i * .27, speed: 100}));
  assert.equal(Q.review(fast).overlapSuspects.length, 0, 'consistently short intervals are a fast rally, not an overlap');
  const mixed = [0, .7, 1.4, 2.1, 2.31, 2.8, 3.5, 4.2, 6.9, 7.6, 8.3, 9.0].map(t => ({t, speed: 55}));
  const r = Q.review(mixed);
  assert(r.overlapSuspects.some(s => s.t === 2.31), 'an isolated short interval seeds a suspect window');
  assert.equal(r.hits.length, mixed.length, 'the count is kept');
  assert.equal(r.hits.find(h => h.t === 2.31).speed, null);
  assert.equal(r.hits.find(h => h.t === 2.31).qualityCode, 'overlap_suspect');
  assert.equal(r.hits.find(h => h.t === 1.4).speed, null, 'neighbours within the span lose their speed');
  assert.equal(r.hits.find(h => h.t === 6.9).speed, 55, 'hits outside the span keep their speed');
  assert.equal(Q.review(mixed, {overrides: {'2.31': 'keep'}}).hits.find(h => h.t === 2.31).speed, 55, 'a manual keep restores the speed');
  assert.equal(Q.review(mixed, {overlapSuspect: false}).overlapSuspects.length, 0, 'the rule can be switched off');
  const tooShort = [0, .7, .85, 1.0, 1.7].map(t => ({t, speed: 55}));
  assert(Q.review(tooShort).overlapSuspects.length > 0, 'intervals below 0.17 s are always suspect');
  console.log('Overlap-suspect review keeps counts and withholds speeds near interleaved sounds');
}
